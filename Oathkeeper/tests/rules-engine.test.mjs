import test from 'node:test';
import assert from 'node:assert/strict';
import {deriveCharacter,powerAtRank,rollAdjustments,applyRollAdjustments,validateEffect} from '../web/rules-engine.js';
import {diceSkinPalette} from '../web/dice-tabletop.js';
import {rollDice} from '../web/dice.js';
import {recordRoll,validateHistory} from '../web/roll-statistics.js';
import {rulesPage,paladinSlotMaximums} from '../web/rules-ui.js';
const character=()=>({level:1,class:'Paladin',str:18,dex:14,con:20,int:12,wis:20,cha:18,armor:16,shield:true,faith:false,aura:false,body:200,speed:30,hpBase:10,hp:15,oil:5,tapers:5,cp:2,sp:0,ep:0,gp:15,pp:0,size:'Medium',powerRanks:[1,1,1],magicEffects:[],items:[['Chainmail',1,55],['Shield with holy symbol',1,6],['Purple cloak',1,3]],exhaustion:0});
test('Strength, level and item changes update all relevant derived values without mutating source',()=>{
 const c=character(),first=deriveCharacter(c);
 assert.equal(first.capacity,270);
 assert.equal(first.proficiency,2);
 assert.equal(first.maxHp,15);
 assert.equal(first.ac,18);
 assert.equal(first.attack,6);
 assert.equal(first.damage,4);
 c.str=20;
 assert.equal(deriveCharacter(c).capacity,300);
 assert.equal(deriveCharacter(c).attack,7);
 assert.equal(deriveCharacter(c).damage,5);
 c.level=5;c.hpBase=34; // base 10 + four average Paladin level gains
 assert.equal(deriveCharacter(c).maxHp,59);
 assert.equal(deriveCharacter(c).proficiency,3);
 assert.equal(deriveCharacter(c).extraAttack,2);
 c.items[1][1]=0;
 assert.equal(deriveCharacter(c).ac,16);
 c.items[0][1]=0;
 assert.equal(deriveCharacter(c).ac,12);
 assert(Math.abs(deriveCharacter(c).weight-(first.weight-61))<1e-8);
 assert.equal(c.hp,15,'derivation never overwrites saved current HP');
});
test('magic bonuses activate only with an existing item, equipped and attuned',()=>{
 const c=character();
 c.items.push(['Gauntlets of Ogre Power',1,2]);
 const e={item:'Gauntlets of Ogre Power',target:'str',op:'minimum',value:19,enabled:true,requiresAttunement:true,attuned:true};
 c.magicEffects=[validateEffect(e)];
 assert.equal(deriveCharacter(c).scores.str,19);
 assert.equal(deriveCharacter(c).capacity,285);
 c.magicEffects[0].attuned=false;
 assert.equal(deriveCharacter(c).scores.str,18);
 c.magicEffects[0].attuned=true;
 c.items[c.items.length-1][1]=0;
 assert.equal(deriveCharacter(c).scores.str,18);
 c.items[c.items.length-1][1]=1;
 c.magicEffects[0].enabled=false;
 assert.equal(deriveCharacter(c).scores.str,18);
 assert.throws(()=>validateEffect({...e,op:'multiply',value:100}),/Multiplier/);
});
test('multipliers apply to chosen roll totals but never change random faces or normal rolls',()=>{
 const c=character();
 c.items.push(['Enchanted token',1,0]);
 c.magicEffects=[validateEffect({item:'Enchanted token',target:'damageMultiplier',op:'multiply',value:2,enabled:true,attuned:false,requiresAttunement:false})];
 const raw=rollDice({sides:8,mode:'official',quantity:1,modifier:0},()=>3);
 assert.equal(raw.rolls[0].value,4);
 const enhanced=applyRollAdjustments(raw,rollAdjustments(c,'damage',8));
 assert.equal(enhanced.total,16);
 assert.equal(enhanced.rawTotal,4);
 assert.equal(enhanced.rolls[0].value,4);
 assert.equal(applyRollAdjustments(raw,rollAdjustments(c,'normal')).total,4);
 const history=validateHistory(recordRoll([],enhanced,1000));
 assert.equal(history[0].total,16);
 assert.deepEqual(history[0].values,[4]);
 c.items.pop();
 assert.equal(applyRollAdjustments(raw,rollAdjustments(c,'damage',8)).total,8);
});
test('bag of holding counts its own weight but not flagged contents; missing bag restores carried weight',()=>{
 const c=character();
 c.items.push(['Bag of Holding',1,5],['Quests and rations',2,30,true]);
 const stored=deriveCharacter(c);
 assert.equal(stored.bagContents,60);
 c.items[3][1]=0;
 const unpacked=deriveCharacter(c);
 assert.equal(unpacked.bagContents,0);
 assert.equal(unpacked.weight,stored.weight+60-5);
});
test('power ranks add chosen dice to homebrew only; standard slots follow Paladin table',()=>{
 const c=character();
 assert.equal(powerAtRank(c,0).notation,'1d8');
 assert.equal(powerAtRank(c,1).notation,'2d8');
 c.powerRanks[0]=3;c.powerRanks[2]=2;
 assert.equal(powerAtRank(c,0).notation,'3d8');
 assert.equal(powerAtRank(c,2).notation,'2d8');
 assert.deepEqual(paladinSlotMaximums(1),[2,0,0,0,0]);
 assert.deepEqual(paladinSlotMaximums(5),[4,2,0,0,0]);
 assert.match(rulesPage(c),/Custom power ranks/);
});
test('the selected dice skin defines animation colors while Stormcaller remains distinct',()=>{
 const purple=diceSkinPalette();
 const red=diceSkinPalette({slug:'dragonfire',accent:'#ec5c25',bg:'#311018'});
 const green=diceSkinPalette({slug:'elvenleaf',accent:'#9bdb6c',bg:'#153b25'});
 const pale=diceSkinPalette({slug:'celestial',accent:'#f2d99c',bg:'#41406b'});
 assert.deepEqual(purple.rgb,[98,100,124]);
 assert.deepEqual(red.rgb,[236,92,37]);
 assert.deepEqual(green.rgb,[155,219,108]);
 assert.deepEqual(pale.rgb,[242,217,156]);
 assert.notDeepEqual(red.rgb,green.rgb);
 assert.deepEqual(diceSkinPalette({accent:'unsafe-url('}).rgb,purple.rgb);
});
test('2024 exhaustion changes game D20 bonuses and speed but not flat damage',()=>{
 const c=character();c.exhaustion=2;
 const d=deriveCharacter(c);
 assert.equal(d.d20Penalty,4);
 assert.equal(d.speed,20);
 assert.equal(d.attack,2);
 assert.equal(d.damage,4);
 assert.equal(rollAdjustments(c,'strengthCheck').add,0);
});
